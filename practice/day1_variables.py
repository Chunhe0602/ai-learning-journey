# 第 1 课练习 1：认识变量
# 变量就是贴了标签的盒子，用来记住数据

name = "春和"           # 字符串：文字
city = "佛山"           # 字符串：文字
work_city = "广州"      # 字符串：文字
days_learning = 1      # 整数：数字
is_fun = True          # 布尔：是 / 否
心情="开心" 
print("我的名字叫", name)
print("我住在", city, "，工作在", work_city)
print("今天是我学 Python 的第", days_learning, "天")
print("学 Python 有趣吗：", is_fun)
print("我的心情是",心情)
# 变量可以被重新赋值（换个内容再装进同一个盒子）
city = "广州"
print("下周我会在", city, "敲代码")
